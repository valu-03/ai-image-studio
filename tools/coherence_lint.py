"""Judge whether a prompt reads as one coherent scene, not keyword salad.

tools/realism_lint.py checks that the right STRUCTURAL trigger words are
present; it cannot tell a real photo description from the same words
shuffled into a list, and it cannot catch two descriptors that flatly
contradict each other. This is the missing semantic half - an LLM judge,
added ALONGSIDE the deterministic gate, never instead of it (the house rule,
CLAUDE.md: "a text model suggests, a linter decides"): a coherent prompt
still has to pass realism_lint's 8/8 to be used, and a "keyword salad"
prompt that fails THIS check can still be regenerated by a human, exactly
like a failed vision_lint result - display-only, never auto-rewritten, and
never given authority to override the deterministic gate.

Usage:
    python tools/coherence_lint.py --prompt "..."

Key: OPENROUTER_API_KEY in .env, same as ask_llm.py - optional everywhere.
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import ask_llm  # noqa: E402

LABELS = {
    "coherent": "Reads as one scene",
    "no_contradictions": "No contradicting descriptors",
    "grammatical": "Natural language, not a keyword list",
}
CHECK_KEYS = tuple(LABELS)

SYSTEM = (
    "You review AI image prompts for a photography app. Judge the prompt on "
    "three things ONLY: whether it reads as one coherent real scene (not a "
    "list of disconnected trigger words stitched together), whether any two "
    "descriptors contradict each other (e.g. \"matte skin\" and \"dewy "
    "glowing skin\" in the same prompt), and whether it is written in "
    "natural language rather than a comma-spliced keyword dump. Do not judge "
    "realism vocabulary, camera gear, or lighting terms - a separate "
    "deterministic check already covers that."
)


def build_prompt(text):
    return (
        "Prompt to review:\n{}\n\n"
        "Return ONLY a JSON object, no prose, no markdown fences, with exactly "
        "these keys: {}. Each value is "
        '{{"match": true|false, "note": "a short reason, one sentence"}}. '
        '"match": true means it PASSES that check (true = coherent, true = no '
        "contradictions, true = grammatical).".format(text, ", ".join(CHECK_KEYS))
    )


def check(text, model=None, ask=None):
    """(checks, score, total, error) - exactly one of (checks, error) is None.

    checks: [{"key", "label", "passed": bool, "fix": str, "ok_text": str}, ...],
    the same shape tools/vision_lint.py and tools/realism_lint.py's checks_for()
    produce, so ui/lint_panel.py can render any of the three identically.

    `ask`, like every other LLM-calling function in this codebase, defaults to
    ask_llm.ask and exists so a test can inject a fake without touching real
    network code.
    """
    ask = ask or ask_llm.ask
    if not (text or "").strip():
        return None, 0, len(CHECK_KEYS), "Nothing to check - the prompt is empty."

    reply, error = ask(build_prompt(text), system=SYSTEM, model=model)
    if error:
        return None, 0, len(CHECK_KEYS), error

    payload = ask_llm.extract_json(reply)
    if not isinstance(payload, dict):
        return None, 0, len(CHECK_KEYS), "The model did not return JSON."

    checks = []
    for key in CHECK_KEYS:
        entry = payload.get(key)
        entry = entry if isinstance(entry, dict) else {}
        passed = bool(entry.get("match"))
        note = str(entry.get("note", "")).strip()
        checks.append({
            "key": key,
            "label": LABELS[key],
            "passed": passed,
            "fix": note or "The model flagged this.",
            "ok_text": note or "Looks fine.",
        })
    score = sum(1 for c in checks if c["passed"])
    return checks, score, len(checks), None


# --------------------------------------------------------------------------- #
def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--prompt", required=True)
    parser.add_argument("--model", help="override the text model id for this call")
    args = parser.parse_args(argv)

    checks, score, total, error = check(args.prompt, model=args.model)
    if error:
        print(error, file=sys.stderr)
        return 3
    for c in checks:
        mark = "PASS" if c["passed"] else "FAIL"
        print("[{}] {}: {}".format(mark, c["label"], c["ok_text"] if c["passed"] else c["fix"]))
    print("{}/{}".format(score, total))
    return 0 if score == total else 1


if __name__ == "__main__":
    sys.exit(main())
